#!/usr/bin/env python3
"""
Build index.yaml (a single-file summary of every HeroDocs record in this repo)
and BUILD-PLAN.md (the CIs organized by CI Group, in build order).

The index flips upstream links into a reverse view (linked_from), groups requirements
by area, lays out each requirement's build order, lists open decisions, maps every ERD field to the CI
that builds it, and reports coverage gaps. Skills and people read this one file
instead of opening every record.

Run from the repo root:  python3 scripts/build_index.py
Check only (no write):   python3 scripts/build_index.py --check
In VS Code:              Cmd+Shift+B rebuilds the index, then validates.

The index is generated. Never edit index.yaml by hand.
"""
import datetime
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("Missing libraries. Run:  pip3 install -r requirements.txt")
    sys.exit(2)

ROOT = Path(__file__).resolve().parent.parent
INDEX_PATH = ROOT / "index.yaml"
PLAN_PATH = ROOT / "BUILD-PLAN.md"

# ci_type -> short code used in CI file names and the build plan
CI_CODES = {
    "module": "MOD", "field": "FLD", "layout": "LAY", "layout_rule": "LRL",
    "validation_rule": "VRL", "workflow_rule": "WFR", "blueprint": "BLU",
    "function": "FNC", "widget": "WDG", "web_form": "WEB", "report": "RPT",
    "dashboard": "DSH", "email_template": "ETPL", "mail_merge_template": "MTPL",
    "inventory_template": "ITPL", "integration": "INT", "other": "OTH",
}

# folder -> (record type, ID prefix)
TYPES = {
    "sources": ("source", "SRC"),
    "requirements": ("requirement", "REQ"),
    "decisions": ("decision", "DD"),
    "erd": ("erd", "ENT"),
    "cis": ("ci", "CI"),
    "ci-groups": ("ci_group", "CG"),
    "stories": ("story", "US"),
    "uat": ("uat", "UAT"),
    "training": ("training", "TRN"),
    "docs": ("documentation", "DOC"),
}
PREFIX_TYPE = {prefix: rtype for rtype, prefix in TYPES.values()}

# Upstream link fields, in the order they're shown.
LINK_FIELDS = ["sources", "requirements", "decisions", "depends_on", "group", "stories", "training", "supersedes"]

HEADER = (
    "# GENERATED by scripts/build_index.py. Do not edit by hand.\n"
    "# Rebuild with Cmd+Shift+B in VS Code, or: python3 scripts/build_index.py\n"
)


def plain(value):
    """Dates become strings and empty values are dropped, matching the validator."""
    if isinstance(value, dict):
        return {k: plain(v) for k, v in value.items() if v is not None and v != ""}
    if isinstance(value, list):
        return [plain(v) for v in value]
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    return value


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end == -1:
        return None
    try:
        data = yaml.safe_load(text[4:end])
    except yaml.YAMLError:
        return None
    if not isinstance(data, dict):
        return None
    data = plain(data)
    data["_body"] = text[end + 4:].split("\n", 1)[1] if "\n" in text[end + 4:] else ""
    return data


def first_paragraph(body):
    """The first paragraph of a record body that isn't a heading."""
    para = []
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            if para:
                break
            continue
        if not stripped:
            if para:
                break
            continue
        para.append(stripped)
    return " ".join(para)


def as_list(value):
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def load_records():
    records = {}
    for folder, (rtype, prefix) in TYPES.items():
        folder_path = ROOT / folder
        if not folder_path.is_dir():
            continue
        for path in sorted(folder_path.glob("*.md")):
            if path.name.lower() == "readme.md":
                continue
            data = frontmatter(path)
            if not data or not isinstance(data.get("id"), str):
                continue
            data["_type"] = rtype
            data["_file"] = str(path.relative_to(ROOT))
            records.setdefault(data["id"], data)
    return records


# Reverse links through these fields get their own label instead of the record type.
REVERSE_LABELS = {"depends_on": "needed_by", "supersedes": "superseded_by"}

CHAIN_ORDER = {prefix: i for i, (_, prefix) in enumerate(TYPES.values())}


def id_sort(ids):
    """Sort IDs in chain order (SRC, REQ, DD, ENT, CI, CG, US, UAT, TRN, DOC), then by number."""
    def key(rid):
        prefix, _, num = rid.partition("-")
        return (CHAIN_ORDER.get(prefix, 99), prefix, int(num) if num.isdigit() else 0)
    return sorted(set(ids), key=key)


def build_order(ci_ids, records):
    """Order CIs so each comes after the CIs it depends on (lowest ID first among ties)."""
    remaining = set(ci_ids)
    done, order = set(), []
    while remaining:
        ready = [c for c in remaining
                 if all(d in done or d not in remaining for d in as_list(records[c].get("depends_on")))]
        if not ready:  # a dependency loop; list the rest by ID so nothing is lost
            ready = list(remaining)
        nxt = id_sort(ready)[0]
        order.append(nxt)
        done.add(nxt)
        remaining.discard(nxt)
    return order


def build():
    records = load_records()

    # Reverse links: target -> {source record type: [ids]}
    linked_from = {rid: {} for rid in records}
    for rid, data in records.items():
        for field in LINK_FIELDS:
            for target in as_list(data.get(field)):
                if target in records:
                    label = REVERSE_LABELS.get(field, data["_type"])
                    linked_from[target].setdefault(label, []).append(rid)

    def back(rid, rtype):
        return id_sort(linked_from.get(rid, {}).get(rtype, []))

    # Records section
    out_records = {}
    for rid in id_sort(records):
        data = records[rid]
        entry = {"type": data["_type"], "title": data.get("title"), "file": data["_file"]}
        for key in ("status", "deploy_status", "area", "module", "app", "ci_type", "api_name", "role", "priority", "playbook"):
            if key in data:
                entry[key] = data[key]
        links = {f: as_list(data[f]) for f in LINK_FIELDS if data.get(f)}
        if links:
            entry["links"] = links
        reverse = {t: id_sort(ids) for t, ids in sorted(linked_from[rid].items())}
        if reverse:
            entry["linked_from"] = reverse
        out_records[rid] = entry

    # Requirements view
    out_reqs = {}
    for rid in id_sort(r for r in records if records[r]["_type"] == "requirement"):
        cis = back(rid, "ci")
        groups = {}
        for ci in cis:
            group = records[ci].get("group")
            if group:
                groups.setdefault(group, []).append(ci)
        external = id_sort(
            d for ci in cis for d in as_list(records[ci].get("depends_on"))
            if d in records and d not in cis
        )
        view = {
            "title": records[rid].get("title"),
            "status": records[rid].get("status"),
            "area": records[rid].get("area"),
            "module": records[rid].get("module"),
            "decisions": back(rid, "decision"),
            "stories": back(rid, "story"),
            "uat": back(rid, "uat"),
            "docs": back(rid, "documentation"),
            "groups": {g: id_sort(ids) for g, ids in sorted(groups.items())},
            "build_order": build_order(cis, records),
        }
        if external:
            view["also_needs"] = external
        out_reqs[rid] = {k: v for k, v in view.items() if v not in ([], {}, None)}

    # Open decisions
    open_decisions = []
    for rid in id_sort(r for r in records if records[r]["_type"] == "decision"):
        if records[rid].get("status") == "proposed":
            item = {"id": rid, "title": records[rid].get("title")}
            waiting = back(rid, "ci")
            if waiting:
                item["waiting_cis"] = waiting
            open_decisions.append(item)

    # Field lookup
    ci_by_field = {}
    for rid, data in records.items():
        if data["_type"] == "ci" and data.get("api_name"):
            ci_by_field.setdefault((data.get("module"), data["api_name"]), []).append(rid)
    fields = {}
    for rid in id_sort(r for r in records if records[r]["_type"] == "erd"):
        erd = records[rid]
        module = erd.get("module")
        for f in erd.get("fields", []) or []:
            if not isinstance(f, dict) or not f.get("api_name"):
                continue
            entry = {"status": f.get("status"), "type": f.get("type")}
            builders = id_sort(ci_by_field.get((module, f["api_name"]), []))
            if builders:
                entry["cis"] = builders
                reqs = id_sort(r for c in builders for r in as_list(records[c].get("requirements")))
                decs = id_sort(d for c in builders for d in as_list(records[c].get("decisions")))
                if reqs:
                    entry["requirements"] = reqs
                if decs:
                    entry["decisions"] = decs
            fields[f"{module}.{f['api_name']}"] = entry

    # Coverage gaps
    reqs = [r for r in records if records[r]["_type"] == "requirement" and records[r].get("status") != "declined"]
    stories = [s for s in records if records[s]["_type"] == "story" and records[s].get("status") != "declined"]
    gaps = {
        "requirements_with_open_questions": id_sort(
            r for r in reqs if "open-questions" in as_list(records[r].get("tags"))
        ),
        "requirements_without_module": id_sort(r for r in reqs if not records[r].get("module")),
        "requirements_without_cis": id_sort(r for r in reqs if not back(r, "ci")),
        "requirements_without_uat": id_sort(r for r in reqs if not back(r, "uat")),
        "requirements_without_docs": id_sort(r for r in reqs if not back(r, "documentation")),
        "stories_without_cis": id_sort(
            s for s in stories if not back(s, "ci") and "no-build" not in as_list(records[s].get("tags"))
        ),
        "stories_without_uat": id_sort(s for s in stories if not back(s, "uat")),
        "stories_without_training": id_sort(s for s in stories if not back(s, "training")),
        "pending_fields_without_ci": sorted(
            k for k, v in fields.items() if v["status"] in ("pending", "flagged") and "cis" not in v
        ),
    }
    gaps = {k: v for k, v in gaps.items() if v}

    counts = {}
    for data in records.values():
        counts[data["_type"]] = counts.get(data["_type"], 0) + 1

    project = {}
    project_path = ROOT / "project.yaml"
    if project_path.exists():
        p = yaml.safe_load(project_path.read_text(encoding="utf-8")) or {}
        project = {k: p[k] for k in ("client", "project", "status") if k in p}

    # Requirements grouped by area, in the order areas are listed in project.yaml
    by_area = {}
    for rid in id_sort(r for r in records if records[r]["_type"] == "requirement"):
        by_area.setdefault(records[rid].get("area") or "(no area)", []).append(rid)
    area_order = list(p.get("areas") or []) if project_path.exists() else []
    areas_view = {a: by_area[a] for a in area_order if a in by_area}
    areas_view.update({a: ids for a, ids in by_area.items() if a not in areas_view})

    index = {
        "project": project,
        "counts": {t: counts[t] for _, (t, _) in TYPES.items() if t in counts},
        "gaps": gaps or "none",
        "open_decisions": open_decisions or "none",
        "areas": areas_view or "none",
        "requirements": out_reqs,
        "fields": fields,
        "records": out_records,
    }
    return HEADER + yaml.safe_dump(index, sort_keys=False, allow_unicode=True, width=1000)


def build_plan():
    """BUILD-PLAN.md: CIs organized by CI Group, in build order, with ungrouped CIs by requirement."""
    records = load_records()
    cis = {r: d for r, d in records.items() if d["_type"] == "ci" and d.get("status") != "declined"}
    groups = {r: d for r, d in records.items() if d["_type"] == "ci_group"}

    # ERD lookup: (module, api_name) -> field entry
    erd_fields = {}
    for d in records.values():
        if d["_type"] == "erd":
            for f in d.get("fields", []) or []:
                if isinstance(f, dict) and f.get("api_name"):
                    erd_fields[(d.get("module"), f["api_name"])] = f

    action_by_status = {"pending": "create", "exists": "modify", "flagged": "remove", "removed": "removed"}

    def ci_line(cid):
        d = cis[cid]
        code = CI_CODES.get(d.get("ci_type"), "?")
        status = d.get("deploy_status", "not_started").replace("_", " ")
        extra = []
        if d.get("stories"):
            extra.append("delivers " + ", ".join(id_sort(as_list(d["stories"]))))
        if d.get("depends_on"):
            extra.append("after " + ", ".join(id_sort(as_list(d["depends_on"]))))
        if d.get("playbook"):
            extra.append("playbook " + d["playbook"])
        tail = f" ({'; '.join(extra)})" if extra else ""
        return f"- **{cid}** [{code}] {d.get('title')} · {d.get('module')} · {status}{tail}"

    def field_lines(cids):
        lines = []
        for cid in cids:
            d = cis[cid]
            if d.get("ci_type") != "field" or not d.get("api_name"):
                continue
            f = erd_fields.get((d.get("module"), d["api_name"]))
            if f:
                action = action_by_status.get(f.get("status"), f.get("status"))
                lines.append(f"- {f.get('label')} (`{d.get('module')}.{d['api_name']}`) [{f.get('type')}]: {action}")
            else:
                lines.append(f"- `{d.get('module')}.{d['api_name']}`: not in the ERD")
        return lines

    out = [
        "<!-- GENERATED by scripts/build_index.py. Do not edit by hand. -->",
        "<!-- Rebuild with Cmd+Shift+B in VS Code, or: python3 scripts/build_index.py -->",
        "",
        "# Build plan",
        "",
    ]
    project_path = ROOT / "project.yaml"
    if project_path.exists():
        p = yaml.safe_load(project_path.read_text(encoding="utf-8")) or {}
        if p.get("client"):
            out += [f"**{p.get('client')}**: {p.get('project', '')}", ""]

    grouped = {g: [] for g in groups}
    ungrouped = []
    for cid in cis:
        g = cis[cid].get("group")
        (grouped[g] if g in grouped else ungrouped).append(cid)

    by_type = {}
    for d in cis.values():
        code = CI_CODES.get(d.get("ci_type"), "?")
        by_type[code] = by_type.get(code, 0) + 1
    out += [
        f"{len(cis)} CIs in {sum(1 for g in grouped if grouped[g])} groups, plus {len(ungrouped)} ungrouped. "
        + ", ".join(f"{k} {v}" for k, v in sorted(by_type.items())) + ".",
        "",
    ]

    if not cis:
        out += ["No CIs yet.", ""]
        return "\n".join(out)

    out += ["## CI Groups", ""]
    for gid in id_sort(grouped):
        members = build_order(grouped[gid], cis) if grouped[gid] else []
        if not members:
            continue
        g = groups[gid]
        reqs = id_sort(r for c in members for r in as_list(cis[c].get("requirements")))
        out += [f"### {gid}: {g.get('title')}", ""]
        meta = [f"{len(members)} CIs"]
        if reqs:
            meta.append("for " + ", ".join(reqs))
        if g.get("clickup_tasks"):
            meta.append("ClickUp " + ", ".join(as_list(g["clickup_tasks"])))
        out += ["*" + " · ".join(meta) + "*", ""]
        fields = field_lines(members)
        if fields:
            out += ["**Fields**", ""] + fields + [""]
        out += ["**CIs, in build order**", ""] + [ci_line(c) for c in members] + [""]
        note = first_paragraph(g.get("_body", ""))
        if note:
            out += ["**Notes**", "", note, ""]

    if ungrouped:
        out += ["## Ungrouped CIs, by requirement", ""]
        by_req = {}
        for cid in ungrouped:
            reqs = id_sort(as_list(cis[cid].get("requirements"))) or ["(no requirement)"]
            by_req.setdefault(reqs[0], []).append(cid)
        for rid in id_sort(r for r in by_req if r != "(no requirement)") + (["(no requirement)"] if "(no requirement)" in by_req else []):
            title = records[rid].get("title") if rid in records else ""
            out += [f"### {rid}" + (f": {title}" if title else ""), ""]
            fields = field_lines(by_req[rid])
            if fields:
                out += fields + [""]
            out += [ci_line(c) for c in build_order(by_req[rid], cis)] + [""]

    out += ["## Full build order", ""]
    for n, cid in enumerate(build_order(list(cis), cis), 1):
        d = cis[cid]
        grp = f" · {d['group']}" if d.get("group") in groups else ""
        out.append(f"{n}. {cid} [{CI_CODES.get(d.get('ci_type'), '?')}] {d.get('title')}{grp}")
    out.append("")
    return "\n".join(out)


def main():
    text = build()
    plan = build_plan()
    if "--check" in sys.argv:
        stale = []
        if (INDEX_PATH.read_text(encoding="utf-8") if INDEX_PATH.exists() else "") != text:
            stale.append("index.yaml")
        if (PLAN_PATH.read_text(encoding="utf-8") if PLAN_PATH.exists() else "") != plan:
            stale.append("BUILD-PLAN.md")
        if stale:
            print(" and ".join(stale) + " out of date. Rebuild with Cmd+Shift+B or: python3 scripts/build_index.py")
            return 1
        print("index.yaml and BUILD-PLAN.md are up to date.")
        return 0
    INDEX_PATH.write_text(text, encoding="utf-8")
    PLAN_PATH.write_text(plan, encoding="utf-8")
    print(f"index.yaml rebuilt ({text.count(chr(10))} lines); BUILD-PLAN.md rebuilt.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

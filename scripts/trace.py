#!/usr/bin/env python3
"""
Generate a throwaway traceability review: one table per capability area, one row
per user story, with four columns: Requirement, User story, Assessment, Delivered by.

The requirement appears on the first row of its stories. The Assessment cells hold
placeholders the herodocs-review skill fills in. The file goes to review/, which git
ignores: it's regenerated on demand and never committed.

Run from the repo root:
  python3 scripts/trace.py                         all requirements
  python3 scripts/trace.py --area "Lead intake"    one capability area
  python3 scripts/trace.py --req REQ-004 REQ-009   specific requirements
"""
import argparse
import datetime
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_index import CI_CODES, ROOT, as_list, build_order, id_sort, load_records  # noqa: E402

PENDING = "_pending_"


def cell(text):
    """Make text safe for a single markdown table cell."""
    return text.replace("|", "\\|").replace("\n", "<br>").strip()


def requirement_points(data):
    """The requirement's body as cell text: no title, no Notes or Open questions sections."""
    out, skip = [], False
    for line in data.get("_body", "").splitlines():
        stripped = line.strip()
        if stripped.startswith("# ") and not out:
            continue
        if stripped.startswith("## "):
            skip = True
            continue
        if skip or not stripped:
            continue
        out.append("• " + stripped[2:] if stripped[:2] in ("- ", "* ") else stripped)
    return "<br>".join(cell(line) for line in out)


def story_sentence(data):
    for block in data.get("_body", "").split("\n\n"):
        block = block.strip()
        if block and not block.startswith("#"):
            return " ".join(line.strip() for line in block.splitlines())
    return ""


def current_branch():
    try:
        return subprocess.run(["git", "branch", "--show-current"], cwd=ROOT,
                              capture_output=True, text=True).stdout.strip() or "(detached)"
    except OSError:
        return "(unknown)"


def marker(rid, key):
    return f"<!--a {rid} {key}-->{PENDING}<!--/a-->"


def main():
    parser = argparse.ArgumentParser(description="Generate a traceability review in review/.")
    parser.add_argument("--area", help="only requirements in this capability area")
    parser.add_argument("--req", nargs="+", help="only these requirement IDs")
    parser.add_argument("--out", help="output path (default review/TRACE-<date>.md)")
    args = parser.parse_args()

    records = load_records()
    active = {r: d for r, d in records.items() if d.get("status") != "declined"}
    reqs = [r for r in id_sort(active) if active[r]["_type"] == "requirement"]
    if args.area:
        reqs = [r for r in reqs if active[r].get("area") == args.area]
    if args.req:
        wanted = {r.upper() for r in args.req}
        reqs = [r for r in reqs if r in wanted]
    if not reqs:
        print("No matching requirements.")
        return 1

    stories = {r: d for r, d in active.items() if d["_type"] == "story"}
    cis = {r: d for r, d in active.items() if d["_type"] == "ci"}

    def ci_list(ids):
        return "<br>".join(cell(f"{c} [{CI_CODES.get(cis[c].get('ci_type'), '?')}] {cis[c].get('title')}")
                           for c in build_order(ids, cis))

    # Areas in project.yaml order
    project = {}
    if (ROOT / "project.yaml").exists():
        import yaml
        project = yaml.safe_load((ROOT / "project.yaml").read_text(encoding="utf-8")) or {}
    order = list(project.get("areas") or [])
    by_area = {}
    for rid in reqs:
        by_area.setdefault(active[rid].get("area") or "(no area)", []).append(rid)
    areas = [a for a in order if a in by_area] + [a for a in by_area if a not in order]

    today = datetime.date.today().isoformat()
    doc = [
        "<!-- GENERATED by scripts/trace.py for review. Throwaway: regenerate any time, never commit. -->",
        "",
        f"# Traceability review: {project.get('client', '')}",
        "",
        f"*{today} · branch `{current_branch()}`*",
        "",
    ]
    story_links = 0
    for area in areas:
        doc += [f"## {area}", "",
                "| Requirement | User story | Assessment | Delivered by |",
                "|---|---|---|---|"]
        for rid in by_area[area]:
            r = active[rid]
            head = f"**{rid}: {cell(r.get('title', ''))}**"
            notes = []
            if "open-questions" in as_list(r.get("tags")):
                notes.append("⚠ rests on open questions")
            if not r.get("module"):
                notes.append("⚠ no module yet")
            req_cell = head + (" · " + " · ".join(notes) if notes else "")
            points = requirement_points(r)
            if points:
                req_cell += "<br>" + points

            rows = []
            for s in [s for s in id_sort(stories) if rid in as_list(stories[s].get("requirements"))]:
                sd = stories[s]
                story_links += 1
                story_cell = f"**{s}** ({cell(sd.get('role', ''))}): {cell(story_sentence(sd))}"
                delivered = [c for c in cis if s in as_list(cis[c].get("stories"))]
                if delivered:
                    by = ci_list(delivered)
                elif "no-build" in as_list(sd.get("tags")):
                    by = "Standard Zoho (no-build)"
                else:
                    by = "⚠ nothing yet"
                rows.append((story_cell, marker(rid, s), by))

            system = [c for c in cis if rid in as_list(cis[c].get("requirements")) and not as_list(cis[c].get("stories"))]
            if system:
                rows.append(("_System behavior (no story)_", marker(rid, "SYSTEM"), ci_list(system)))
            if not rows:
                rows.append(("⚠ _No stories_", marker(rid, "NONE"), ""))

            for i, (story_cell, assessment, by) in enumerate(rows):
                doc.append(f"| {req_cell if i == 0 else ''} | {story_cell} | {assessment} | {by} |")
        doc.append("")

    doc += ["## Overall", "", f"<!--a OVERALL-->{PENDING}<!--/a-->", ""]

    out_path = Path(args.out) if args.out else ROOT / "review" / f"TRACE-{today}.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(doc), encoding="utf-8")
    shown = out_path.relative_to(ROOT) if out_path.is_relative_to(ROOT) else out_path
    print(f"Wrote {shown}: {len(reqs)} requirements, {story_links} story links.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
